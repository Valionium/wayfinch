const assert=require('node:assert/strict');
const {appVM}=require('./app-vm.cjs');
let checks=0;
const check=(value,message)=>{assert.ok(value,message);checks++;};
(async()=>{
  const q=appVM(),{run}=q;
  run(`
    const qaPlan=captureDraft();
    qaPlan.trip.place={name:'Heidelberg',lat:49.4,lon:8.7,elev:115};
    qaPlan.trip.place2={name:'Route end',lat:50.4,lon:9.7,elev:515};
    qaPlan.settings={theme:'light',packEff:.94};
    qaPlan.packed={tent:true};qaPlan.qty={tent:2};qaPlan.custom={tent:{L:7,kg:2,rigid:35}};
    const qaPoints=n=>Array.from({length:n},(_,i)=>{const t=i/(n-1);return {lat:49.4+t,lon:8.7+t,elev:115+400*t,t,km:100*t};});
    qaPlan.gpx={pts:qaPoints(2000),mapPts:qaPoints(5000),km:100,distanceKm:100,ascent:400,hadElev:true,elevationSource:'file',name:'Maximal saved route',file:'route.gpx'};
    const qaSetup=i=>normaliseSetup({...qaPlan,id:'qa_'+i,name:'Trip '+i,saved:'2026-10-03',predicted:{mounted:35,kit:31,spare:4,spilled:0,kg:14},thumb:''});
    SETUPS=Array.from({length:20},(_,i)=>qaSetup(i));
    FEEDBACK=Array.from({length:750},(_,i)=>({at:new Date(Date.UTC(2026,0,1)+i).toISOString(),kind:'feedback',step:1,message:'Message '+i,context:'QA',packEff:.88,sent:false}));
    const qaExport=exportAll();
    const qaBytes=importByteLength(qaExport);
    SETUPS=[];FEEDBACK=[];
  `);
  check(run('qaBytes>5000000 && qaBytes<MAX_IMPORT_BYTES'),'20 maximal GPX setups fit the shared import bound');
  const result=await run('importAll(qaExport)');
  check(run('SETUPS.length===20 && FEEDBACK.length===750'),'all 20 maximal GPX setups and 750 reports round trip');
  check(run('SETUPS.every(s=>s.gpx.pts.length===2000 && s.gpx.mapPts.length===5000)'),'all GPX geometry preserved');
  check(!/Skipped/.test(result),'supported full export has no skipped data');
  check(run('SETUPS[0].packed.tent && SETUPS[0].qty.tent===2 && SETUPS[0].custom.tent.L===7'),'ticks, quantities and custom sizes round trip');
  check(run('IMPORTED_SETTINGS.theme===S.theme && IMPORTED_DRAFT!==null'),'import stages the current draft and settings');
  await run('importAll(qaExport)');
  check(run('SETUPS.length===20 && FEEDBACK.length===750'),'reimport is idempotent');
  await run(`importAll(JSON.stringify({feedback:[{at:'2026-10-03T12:00:00.000Z',kind:'feedback',step:1,message:'One',packEff:.88},{at:'2026-10-03T12:00:00.000Z',kind:'feedback',step:1,message:'Two',packEff:.88}]}))`);
  check(run('FEEDBACK.filter(f=>f.at===\'2026-10-03T12:00:00.000Z\').length===2'),'same timestamp does not discard distinct reports');
  check((await run('importAll("{broken")')).includes('parse'),'invalid JSON rejected');
  check((await run('importAll(JSON.stringify({app:"another-app",settings:{theme:"light"}}))')).includes('not a Load Check'),'wrong app rejected');
  check((await run('importAll("界".repeat(Math.floor(MAX_IMPORT_BYTES/3)+1))')).includes('64 MiB'),'UTF-8 byte bound matches File.size for multibyte text');
  check(q.html.includes('if(f.size > MAX_IMPORT_BYTES)') && q.html.includes("$('impMsg').textContent = IMPORT_SIZE_MESSAGE"),'file picker and parser use identical limits');
  const excess=await run('importAll(JSON.stringify({setups:Array.from({length:22},(_,i)=>qaSetup(i+100))}))');
  // 20 trip setups are here already; the trip setups' limit is 40 (the owner's answer of 8 Nov 2026, 20 general and 40 trip setups)
  check(run('SETUPS.length===40') && /Skipped 2 setups/.test(excess),'over-capacity setup cards are bounded and explicitly reported');
  const hostile=await run(`importAll('{"settings":{"theme":"dark"},"__proto__":{"polluted":true},"setups":[null,{},42],"feedback":[{},null]}')`);
  check(/Skipped 5 invalid/.test(hostile) && run('({}).polluted===undefined'),'malformed entries and prototype keys are discarded');
  run('DRAFT_READY=true;DRAFT_READ_KIND="browser";DRAFT_SIGNATURE=JSON.stringify(captureDraft());initialiseDraftSaveStatus();S.nights=8;');
  const flush=run('flushDraft()');
  check(JSON.parse(q.values.get('loadcheck:draft')).trip.nights===8,'draft writes synchronously before promise completion');
  await flush;
  check(run('DRAFT_SAVE_STATUS.state==="saved" && DRAFT_SAVE_STATUS.kind==="browser"'),'draft durability is reported accurately');
  const actualSet=q.context.window.localStorage.setItem;
  q.context.window.localStorage.setItem=()=>{throw Error('Quota exceeded');};
  run('S.nights=9');await run('flushDraft()');
  check(run('DRAFT_SAVE_STATUS.state==="failed"'),'quota failure is visible and not marked durable');
  check(JSON.parse(q.values.get('loadcheck:draft')).trip.nights===8,'quota failure leaves previous durable draft intact');
  check((await run('store.get(DRAFT_KEY)')).trip.nights===8 && run('DRAFT_READ_KIND==="browser"'),'full storage still reads the existing durable plan instead of requiring a spare write');
  await run('renameSetup(SETUPS[0].id,"Renamed while full")');
  check(run('SAVE_MESSAGE.includes("session only")'),'rename quota failure shows session-only state');
  await run('saveSetupNote(SETUPS[0].id,"A note while storage is full")');
  check(run('SETUPS[0].note==="A note while storage is full" && SAVE_MESSAGE.includes("session only")') && q.nodes.get('saveMsg').textContent.includes('session only'),'note quota failure keeps the edit in this session and shows why it is not durable');
  await run('deleteSetup(SETUPS[0].id)');
  check(run('SAVE_MESSAGE.includes("session only")'),'delete quota failure shows session-only state');
  await run('undoDeleteSetup()');
  check(run('SAVE_MESSAGE.includes("session only")'),'undo quota failure shows session-only state');
  const importFailure=await run('importAll(JSON.stringify({settings:{theme:"dark"}}))');
  check(/session only/.test(importFailure),'import quota failure shows session-only state');
  q.nodes.get('draftNew').dataset.confirm='yes';
  await q.nodes.get('draftNew').onclick();
  check(q.nodes.get('draftText').textContent.includes('Could not clear') && run('DRAFT_READY'),'failed Clear plan keeps the current plan open');
  q.context.window.localStorage.setItem=actualSet;
  await run('flushDraft()');
  check(run('DRAFT_SAVE_STATUS.state==="saved"') && JSON.parse(q.values.get('loadcheck:draft')).trip.nights===9,'same failed draft is retried successfully');
  run('DRAFT_READY=false');
  check(run('setPackedItem("tent",true)===false'),'ticks cannot change before draft loading finishes');
  run('DRAFT_READY=true');
  check(run('setPackedItem("not-an-item",true)===false'),'unknown checklist ids are rejected');
  const id=run('getChecklistModel().items[0].id');q.context.qaTickId=id;
  check(run('setPackedItem(qaTickId,true)'),'active checklist item can be packed');
  check(JSON.parse(q.values.get('loadcheck:draft')).packed[id]===true,'packed tick is durable immediately');
  run('CHECKLIST_UNPACKED_ONLY=true;renderPrintableChecklist()');
  check((q.nodes.get('printChecklist').innerHTML.match(/class="print-item"/g)||[]).length===run('getChecklistModel().items.length'),'print includes all selected items even when screen is filtered');
  check(q.nodes.get('printChecklist').innerHTML.includes('✓'),'print retains packed state');
  run('S.pendingSaveName="<script>bad()</script>";');
  check(run('normalisePlan(JSON.parse(JSON.stringify(captureDraft()))).pendingSaveName===S.pendingSaveName'),'text stays data through normalization');
  q.context.window.storage={async set(){throw Error('Account unavailable');},async get(){return {value:'null'};}};
  run('S.nights=12');await run('flushDraft()');
  check(run('DRAFT_SAVE_STATUS.kind==="browser" && DRAFT_SAVE_STATUS.state==="saved"'),'failed account save falls back to durable browser storage');
  check((await run('store.get(DRAFT_KEY)')).trip.nights===12,'newer browser fallback takes priority over older account draft');
  const hostWrites=[];
  q.context.window.storage={async set(key,value){hostWrites.push(JSON.parse(value));},async get(){return {value:'null'};}};
  run('S.nights=13;flushDraft();S.nights=14;flushDraft();');await run('DRAFT_WRITES');
  check(hostWrites.length===1 && hostWrites[0].trip.nights===14,'queued obsolete account drafts are skipped');
  check(run('DRAFT_SAVE_STATUS.state==="saved" && DRAFT_SAVE_STATUS.kind==="host" && DRAFT_SAVE_STATUS.serial===JSON.stringify(captureDraft())'),'latest account completion matches current plan');
  const actions=appVM(),act=actions.run;
  act(`const qaSaved=normaliseSetup({...captureDraft(),id:'action_setup',name:'QA setup',saved:'2026-10-03',predicted:{mounted:35,kit:31,spare:4,spilled:0,kg:14}});SETUPS=[qaSaved];
    snapshotSetup=()=>({...qaSaved,id:newSetupId(),name:'New setup'});`);
  actions.context.window.localStorage.setItem=()=>{throw Error('Quota exceeded');};
  await act('saveSetup("New setup","")');
  check(act('SETUPS.length===2 && SAVE_MESSAGE.includes("session only")'),'new setup quota failure keeps an explicitly session-only copy');
  await act('duplicateSetup("action_setup")');
  check(act('SETUPS.length===3 && SAVE_MESSAGE.includes("session only")'),'duplicate quota failure shows session-only state');
  act('SETUP_ACTION={id:"action_setup",kind:"update",snapshot:{...qaSaved,trip:{...qaSaved.trip,nights:4}}}');
  await act('confirmSetupUpdate("action_setup")');
  check(act('SETUPS.find(s=>s.id==="action_setup").trip.nights===4 && SAVE_MESSAGE.includes("session only")'),'reviewed update quota failure shows session-only state');
  // Two tabs (design 8.5, rules 2, 3, 6, 7): compare before every write, strictly newer versions, setups merged, account value read back.
  const {sharedStore}=require('./app-vm.cjs');
  const shared=sharedStore(),tabA=appVM({storage:shared}),tabB=appVM({storage:shared});
  for(const t of [tabA,tabB])t.run('DRAFT_READY=true;DRAFT_READ_KIND="browser";DRAFT_SIGNATURE=JSON.stringify(captureDraft());initialiseDraftSaveStatus();');
  shared.vms.delete(tabB);   // tab B is frozen: it gets no storage event
  tabA.run('S.nights=3;flushDraft();');
  const firstVersion=JSON.parse(shared.values.get('loadcheck:draft')).updatedAt;
  tabB.run('S.nights=9;flushDraft();');
  check(JSON.parse(shared.values.get('loadcheck:draft')).trip.nights===3,'compare-before-write: a tab that never read the stored version does not overwrite it');
  check(tabB.run('DRAFT_SAVE_STATUS.state')==='conflict','the refused write is reported as a conflict, not as a storage failure');
  shared.vms.add(tabB);
  tabA.run('Date.now=()=>Date.parse("2040-01-01T00:00:00.000Z");S.nights=4;flushDraft();S.nights=5;flushDraft();');
  const lastVersion=JSON.parse(shared.values.get('loadcheck:draft')).updatedAt;
  check(Date.parse(lastVersion)===Date.parse("2040-01-01T00:00:00.000Z")+1&&Date.parse(lastVersion)>Date.parse(firstVersion),'rule 3: with a stopped clock, each write is 1 ms later than the version it replaces');
  const accountWrites=[],accountTab=appVM();
  accountTab.run('DRAFT_READY=true;DRAFT_SIGNATURE=JSON.stringify(captureDraft());DRAFT_VERSION="2020-01-01T00:00:00.000Z";initialiseDraftSaveStatus();');
  accountTab.context.window.storage={async set(key,value){accountWrites.push(value);},async get(){return {value:JSON.stringify({updatedAt:'2030-06-06T00:00:00.000Z',trip:{nights:2}})};}};
  accountTab.run('S.nights=11;flushDraft();');await accountTab.run('DRAFT_WRITES');
  check(accountWrites.length===0,'rule 7: an account value newer than this tab\'s version is not overwritten');
  const setupTabs=[appVM({storage:sharedStore()})];setupTabs.push(appVM({storage:setupTabs[0].store}));
  const [sa,sb]=setupTabs;
  for(const t of setupTabs)t.run('DRAFT_READY=true;snapshotSetup=(name)=>normaliseSetup({...captureDraft(),id:newSetupId(),name,saved:"2026-10-03",predicted:{mounted:35,kit:31,spare:4,spilled:0,kg:14}});');
  await sa.run('saveSetup("From tab A","")');
  await sb.run('saveSetup("From tab B","")');
  const names=JSON.parse(sa.run('JSON.stringify(storedSetupsLocal())')).map(x=>x.name).sort();   // as the page reads its two lists
  check(names.join('|')==='From tab A|From tab B','rule 6: saving a setup keeps the setups another tab saved');
  check(sa.run('SETUPS.length')===2,'rule 6: the other tab follows the setups list without writing');
  console.log(JSON.stringify({suite:'storage',checks,maximal20SetupExportBytes:run('qaBytes'),reportsRoundTripped:750}));
})().catch(error=>{console.error(error);process.exitCode=1;});
